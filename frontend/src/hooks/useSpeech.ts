/**
 * React binding for the speech controller.
 *
 * Components never talk to a speech provider directly: they read the shared
 * state (`idle` / `generating` / `speaking` / error) and call `speak` /
 * `stop` / `retry`. That keeps provider selection and cancellation logic in one
 * place and makes it impossible for a component to announce speech it did not
 * actually trigger.
 */

import { useCallback, useEffect, useState } from 'react'
import { ttsController } from '../services/tts'
import type { SpeechLanguage, SpeechState } from '../services/tts'

export interface UseSpeech {
  phase: SpeechState['phase']
  /** Language of the most recent speech request. */
  language: SpeechLanguage | null
  /** Provider that produced the audio ('browser' | 'local' | null). */
  provider: SpeechState['provider']
  /** True while audio is being generated by a local engine. */
  isGenerating: boolean
  /** True while audio is playing. */
  isSpeaking: boolean
  /** Per-language capability, resolved by `refreshAvailability()`. */
  availability: SpeechState['availability']
  /** True once the browser voice list has been resolved. */
  voicesReady: boolean
  error: SpeechState['error']
  speak: (
    text: string,
    language: SpeechLanguage,
    overrides?: { rate?: number; pitch?: number; dedupeKey?: string; force?: boolean },
  ) => Promise<void>
  stop: () => void
  /** Re-probe providers after the user changes the setup. */
  retry: () => Promise<void>
  refresh: () => Promise<void>
}

export function useSpeech(controller = ttsController): UseSpeech {
  const [state, setState] = useState<SpeechState>(() => controller.getState())

  useEffect(() => controller.subscribe(setState), [controller])

  // Probe once on mount so the UI knows what can actually be spoken before the
  // user presses anything.
  useEffect(() => {
    void controller.refreshAvailability()
  }, [controller])

  const speak = useCallback<UseSpeech['speak']>(
    async (text, language, overrides) => {
      await controller.speak(text, language, overrides)
    },
    [controller],
  )

  const stop = useCallback(() => controller.stop(), [controller])

  const retry = useCallback(async () => {
    await controller.retry()
  }, [controller])

  const refresh = useCallback(async () => {
    await controller.refreshAvailability()
  }, [controller])

  return {
    phase: state.phase,
    language: state.language,
    provider: state.provider,
    isGenerating: state.phase === 'generating',
    isSpeaking: state.phase === 'speaking',
    availability: state.availability,
    voicesReady: state.voicesReady,
    error: state.error,
    speak,
    stop,
    retry,
    refresh,
  }
}